/**
 * Computes Special Move cooldown in seconds scaled directly by move strength
 * (total damage across hits + knockback + hitstun), ranging from 3.5s to 9.5s.
 */
export function getSpecialCooldownSeconds(spec: SpecialMoveSpec): number {
  const power = spec.damage * spec.hits + spec.knockback / 32 + spec.hitstun / 50;
  const raw = 0.5 + power * 0.12;
  return Math.round(Math.min(9.5, Math.max(3.5, raw)) * 10) / 10;
}
